package geometry

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"

	m32 "creaddinscart.studio.go.sl/3d-x-2/math32"
)

// LoadOBJ parses a Wavefront OBJ from an io.Reader. Supports v/vn/vt/f with the
// forms "i", "i/j", "i//k" and "i/j/k" plus negative indices; n-gon faces are
// fan-triangulated.
func LoadOBJ(r io.Reader) (*Mesh, error) {
	var vs []m32.Vec3
	var vns []m32.Vec3
	var vts []m32.Vec2
	m := New()

	type key struct{ v, vt, vn int }
	cache := map[key]uint32{}
	addCorner := func(a, b, c int) uint32 {
		k := key{a, b, c}
		if idx, ok := cache[k]; ok {
			return idx
		}
		nrm := m32.V3(0, 1, 0)
		if c >= 0 {
			nrm = vns[c]
		}
		uv := m32.Vec2{}
		if b >= 0 {
			uv = vts[b]
		}
		idx := uint32(len(m.Vertices))
		m.Vertices = append(m.Vertices, Vertex{vs[a], nrm, uv})
		cache[k] = idx
		return idx
	}
	parseIdx := func(tok string, size int) int {
		n, _ := strconv.Atoi(tok)
		if n < 0 {
			return size + n
		}
		return n - 1
	}

	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		switch f[0] {
		case "v":
			x, _ := strconv.ParseFloat(f[1], 32)
			y, _ := strconv.ParseFloat(f[2], 32)
			z, _ := strconv.ParseFloat(f[3], 32)
			vs = append(vs, m32.V3(float32(x), float32(y), float32(z)))
		case "vn":
			x, _ := strconv.ParseFloat(f[1], 32)
			y, _ := strconv.ParseFloat(f[2], 32)
			z, _ := strconv.ParseFloat(f[3], 32)
			vns = append(vns, m32.V3(float32(x), float32(y), float32(z)))
		case "vt":
			u, _ := strconv.ParseFloat(f[1], 32)
			vv, _ := strconv.ParseFloat(f[2], 32)
			vts = append(vts, m32.V2(float32(u), float32(vv)))
		case "f":
			var corners []uint32
			for _, tok := range f[1:] {
				parts := strings.Split(tok, "/")
				vi := parseIdx(parts[0], len(vs))
				vti, vni := -1, -1
				if len(parts) > 1 && parts[1] != "" {
					vti = parseIdx(parts[1], len(vts))
				}
				if len(parts) > 2 && parts[2] != "" {
					vni = parseIdx(parts[2], len(vns))
				}
				corners = append(corners, addCorner(vi, vti, vni))
			}
			for i := 1; i+1 < len(corners); i++ {
				m.Indices = append(m.Indices, corners[0], corners[i], corners[i+1])
			}
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(vs) == 0 || len(m.Indices) == 0 {
		return nil, fmt.Errorf("geometry: OBJ contained no geometry")
	}
	allZero := true
	for _, v := range m.Vertices {
		if v.Normal != m32.Zero3 {
			allZero = false
			break
		}
	}
	if allZero {
		m.ComputeNormals()
	}
	return m, nil
}

// LoadOBJFile loads an OBJ from a filesystem path.
func LoadOBJFile(path string) (*Mesh, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return LoadOBJ(f)
}

// WriteOBJ writes the mesh as a Wavefront OBJ stream.
func (m *Mesh) WriteOBJ(w io.Writer) error {
	bw := bufio.NewWriter(w)
	defer bw.Flush()
	fmt.Fprintf(bw, "# Generated by 3d-x-2 (CREADDINSCART STUDIO)\n")
	for _, v := range m.Vertices {
		fmt.Fprintf(bw, "v %g %g %g\n", v.Position.X, v.Position.Y, v.Position.Z)
	}
	for _, v := range m.Vertices {
		fmt.Fprintf(bw, "vn %g %g %g\n", v.Normal.X, v.Normal.Y, v.Normal.Z)
	}
	for _, v := range m.Vertices {
		fmt.Fprintf(bw, "vt %g %g\n", v.UV.X, v.UV.Y)
	}
	for i := 0; i+2 < len(m.Indices); i += 3 {
		a := m.Indices[i] + 1
		b := m.Indices[i+1] + 1
		c := m.Indices[i+2] + 1
		fmt.Fprintf(bw, "f %d/%d/%d %d/%d/%d %d/%d/%d\n", a, a, a, b, b, b, c, c, c)
	}
	return nil
}

// SaveOBJ writes the mesh to an OBJ file on disk.
func (m *Mesh) SaveOBJ(path string) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return m.WriteOBJ(f)
}
